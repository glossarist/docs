#!/usr/bin/env python3
"""Generate the GLOSS 1.0 normative class/property annex tables from the ontology TTL.

The spec stays in SSOT sync with concept-model: this script reads
ontologies/glossarist.ttl (41 classes, 171 properties) and renders the
AsciiDoc annex tables the specification includes. Re-run after any
ontology change and commit the refreshed annexes:

    python3 spec/tools/generate_tables.py <path/to/glossarist.ttl>

    # workspace default: the sibling concept-model checkout
    python3 spec/tools/generate_tables.py

Requires: python3 with rdflib (pyshacl's dependency).

Outputs (committed):
    spec/gloss-1.0-classes.adoc
    spec/gloss-1.0-properties.adoc
"""

import os
import sys

GLOSS = "https://www.glossarist.org/ontologies/"
HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(os.path.dirname(HERE), ".")

DEFAULT_SOURCES = [
    os.path.join(HERE, "..", "..", "..", "concept-model", "ontologies", "glossarist.ttl"),
    os.path.expanduser("~/src/glossarist/concept-model/ontologies/glossarist.ttl"),
]

PREFIXES = {
    "https://www.glossarist.org/ontologies/": "gloss",
    "http://www.w3.org/2004/02/skos/core#": "skos",
    "http://www.w3.org/2008/05/skos-xl#": "skosxl",
    "http://purl.org/iso25964/skos-thes#": "iso-thes",
    "http://purl.org/dc/terms/": "dcterms",
    "http://www.w3.org/ns/prov#": "prov",
    "http://www.w3.org/2001/XMLSchema#": "xsd",
    "http://www.w3.org/1999/02/22-rdf-syntax-ns#": "rdf",
    "http://www.w3.org/2002/07/owl#": "owl",
}

PROPERTY_TYPES = [
    ("http://www.w3.org/2002/07/owl#ObjectProperty", "owl:ObjectProperty"),
    ("http://www.w3.org/2002/07/owl#DatatypeProperty", "owl:DatatypeProperty"),
    ("http://www.w3.org/2002/07/owl#TransitiveProperty", "owl:TransitiveProperty"),
]


def compact(iri):
    for ns, prefix in PREFIXES.items():
        if iri.startswith(ns):
            return f"{prefix}:{iri[len(ns):]}"
    return f"<{iri}>"


def range_label(graph, prop):
    for _, _, rng in graph.triples((prop, rdfs("range"), None)):
        return compact(str(rng))
    return "—"


def domain_labels(graph, prop):
    domains = []
    for _, _, dom in graph.triples((prop, rdfs("domain"), None)):
        union = graph.value(dom, owl("unionOf"))
        if union is not None:
            items = []
            cur = union
            first, rest = rdf("first"), rdf("rest")
            while cur is not None and str(cur) != "http://www.w3.org/1999/02/22-rdf-syntax-ns#nil":
                item = graph.value(cur, first)
                if item is None:
                    break
                items.append(compact(str(item)))
                cur = graph.value(cur, rest)
            domains.extend(items)
        else:
            domains.append(compact(str(dom)))
    return ", ".join(domains) if domains else "—"


def rdf(local):
    # rdf: terms — http://www.w3.org/1999/02/22-rdf-syntax-ns#
    from rdflib import URIRef
    return URIRef(f"http://www.w3.org/1999/02/22-rdf-syntax-ns#{local}")


def rdfs(local):
    # rdfs: terms — http://www.w3.org/2000/01/rdf-schema#
    from rdflib import URIRef
    return URIRef(f"http://www.w3.org/2000/01/rdf-schema#{local}")


def owl(local):
    from rdflib import URIRef
    return URIRef(f"http://www.w3.org/2002/07/owl#{local}")


def load_graph(path):
    try:
        from rdflib import Graph
    except ImportError:
        sys.exit("rdflib is required: python3 -m pip install pyshacl (brings rdflib)")
    return Graph().parse(path, format="turtle")


def anchor(name):
    return name.lower().replace("_", "-")


def generate_classes(graph):
    classes = sorted(
        str(s)[len(GLOSS):]
        for s in graph.subjects(rdf("type"), owl("Class"))
        if str(s).startswith(GLOSS)
    )
    lines = [
        "// AUTO-GENERATED by spec/tools/generate_tables.py from glossarist.ttl — DO NOT EDIT.",
        f"// {len(classes)} classes.",
        "",
        "[cols=\"1,1,3\",options=\"header\"]",
        "|===",
        "|Class |Type |Definition",
        "",
    ]
    for name in classes:
        subject = URIRef_of(f"{GLOSS}{name}")
        comment = graph.value(subject, rdfs("comment"))
        text = one_line(str(comment).strip()) if comment else "—"
        lines.append(f"|`gloss:{name}` |owl:Class |{text}")
    lines += ["|===", ""]
    return "\n".join(lines), len(classes)


def generate_properties(graph):
    props = {}  # name -> {types, domains, range, comment}
    for type_iri, type_label in PROPERTY_TYPES:
        for s in graph.subjects(rdf("type"), URIRef_of(type_iri)):
            iri = str(s)
            if not iri.startswith(GLOSS):
                continue
            name = iri[len(GLOSS):]
            entry = props.setdefault(name, {"types": set()})
            entry["types"].add(type_label)
            comment = graph.value(s, rdfs("comment"))
            if comment is not None:
                entry["comment"] = one_line(str(comment).strip())
            entry["domains"] = domain_labels(graph, s)
            entry["range"] = range_label(graph, s)

    ordered = sorted(props.items())
    lines = [
        "// AUTO-GENERATED by spec/tools/generate_tables.py from glossarist.ttl — DO NOT EDIT.",
        f"// {len(ordered)} properties.",
        "",
        "[cols=\"1,1,1,1,3\",options=\"header\"]",
        "|===",
        "|Property |Type |Domain(s) |Range |Definition",
        "",
    ]
    for name, p in ordered:
        type_label = ", ".join(sorted(p["types"]))
        comment = p.get("comment", "—")
        lines.append(
            f"|`gloss:{name}` |{type_label} |{p['domains']} |{p['range']} |{comment}"
        )
    lines += ["|===", ""]
    return "\n".join(lines), len(ordered)


def URIRef_of(iri):
    from rdflib import URIRef
    return URIRef(iri)


def one_line(text):
    text = " ".join(text.split())
    return escape_adoc(text) if text else "—"


def escape_adoc(text):
    return text.replace("|", "\\|")


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else None
    if path is None:
        for candidate in DEFAULT_SOURCES:
            if os.path.exists(candidate):
                path = candidate
                break
    if not path or not os.path.exists(path):
        sys.exit(f"ontology not found; pass the path: {sys.argv[0]} <glossarist.ttl>")

    graph = load_graph(path)

    classes_adoc, n_classes = generate_classes(graph)
    props_adoc, n_props = generate_properties(graph)

    with open(os.path.join(OUT_DIR, "gloss-1.0-classes.adoc"), "w") as f:
        f.write(classes_adoc)
    with open(os.path.join(OUT_DIR, "gloss-1.0-properties.adoc"), "w") as f:
        f.write(props_adoc)

    print(f"OK: wrote gloss-1.0-classes.adoc ({n_classes} classes), "
          f"gloss-1.0-properties.adoc ({n_props} properties) from {path}")


if __name__ == "__main__":
    main()
